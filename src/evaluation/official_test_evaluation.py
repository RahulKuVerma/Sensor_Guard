
"""
SensorGuard — Official C-MAPSS Test Evaluation

Evaluates the saved FD001, FD002, FD003, and FD004 LSTM checkpoints.

Protocol:
- Loads each subset's existing checkpoint.
- Reconstructs the existing engine-level train/validation split.
- Fits the scaler on training engines only, using the existing pipeline.
- Evaluates official test windows using official terminal RUL targets.
- Does not retrain, tune, or modify checkpoints.
- Saves metrics, predictions, confusion matrices, and a summary.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib
matplotlib.use("Agg")

import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import torch
from sklearn.metrics import (
    accuracy_score,
    average_precision_score,
    brier_score_loss,
    confusion_matrix,
    f1_score,
    log_loss,
    precision_score,
    recall_score,
    roc_auc_score,
)

from src.data.loader import load_dataset
from src.features.dataset_builder import (
    prepare_training_validation_test,
)
from src.models.baseline import create_baseline_model


# ============================================================
# Configuration
# ============================================================

PROJECT_ROOT = Path(__file__).resolve().parents[2]

SUBSETS = ["FD001", "FD002", "FD003", "FD004"]

SENSOR_COLUMNS = [f"sensor_{i}" for i in range(1, 22)]

HORIZON = 30
WINDOW_SIZE = 30
STRIDE = 1

TRAIN_RATIO = 0.85
VALIDATION_RATIO = 0.15
RANDOM_SEED = 42

BATCH_SIZE = 256
THRESHOLD = 0.50

HIDDEN_SIZE = 128
NUM_LAYERS = 2
DROPOUT = 0.30

DEVICE = torch.device(
    "cuda" if torch.cuda.is_available() else "cpu"
)


# ============================================================
# Load the existing model
# ============================================================

def load_baseline(checkpoint_path: Path) -> torch.nn.Module:
    """Load an existing trained checkpoint without retraining."""

    if not checkpoint_path.exists():
        raise FileNotFoundError(
            f"Checkpoint not found: {checkpoint_path}"
        )

    model = create_baseline_model(
        input_size=len(SENSOR_COLUMNS),
        hidden_size=HIDDEN_SIZE,
        num_layers=NUM_LAYERS,
        dropout=DROPOUT,
    )

    # These checkpoints were generated by this local project.
    try:
        checkpoint = torch.load(
            checkpoint_path,
            map_location=DEVICE,
            weights_only=True,
        )
    except TypeError:
        checkpoint = torch.load(
            checkpoint_path,
            map_location=DEVICE,
        )

    if (
        isinstance(checkpoint, dict)
        and "model_state_dict" in checkpoint
    ):
        state_dict = checkpoint["model_state_dict"]
    else:
        state_dict = checkpoint

    model.load_state_dict(state_dict)
    model.to(DEVICE)
    model.eval()

    return model


# ============================================================
# Predict probabilities
# ============================================================

def predict_probabilities(
    model: torch.nn.Module,
    X: np.ndarray,
) -> np.ndarray:
    """Predict positive-class probabilities in batches."""

    if len(X) == 0:
        raise ValueError("No test windows were generated.")

    if not np.isfinite(X).all():
        raise ValueError(
            "Test windows contain NaN or infinite values."
        )

    probabilities = []

    with torch.inference_mode():
        for start in range(0, len(X), BATCH_SIZE):
            batch = torch.as_tensor(
                X[start:start + BATCH_SIZE],
                dtype=torch.float32,
                device=DEVICE,
            )

            logits = model(batch)

            # The baseline is expected to return one logit
            # per window. Convert logits to probabilities.
            logits = logits.reshape(-1)
            batch_probabilities = torch.sigmoid(logits)

            probabilities.extend(
                batch_probabilities.cpu().numpy().tolist()
            )

    return np.asarray(probabilities, dtype=np.float64)


# ============================================================
# Metrics
# ============================================================

def calculate_metrics(
    y_true: np.ndarray,
    probabilities: np.ndarray,
    threshold: float = THRESHOLD,
) -> tuple[dict, np.ndarray]:
    """Calculate classification and probability-quality metrics."""

    y_true = np.asarray(y_true).astype(int).reshape(-1)
    probabilities = np.asarray(
        probabilities, dtype=np.float64
    ).reshape(-1)

    if len(y_true) != len(probabilities):
        raise ValueError(
            "Number of labels does not match predictions."
        )

    if not np.isfinite(probabilities).all():
        raise ValueError(
            "Predicted probabilities contain non-finite values."
        )

    if not set(np.unique(y_true)).issubset({0, 1}):
        raise ValueError("Test labels must be binary (0 or 1).")

    if len(np.unique(y_true)) != 2:
        raise ValueError(
            "AUROC and AUPRC require both classes in the test labels."
        )

    probabilities = np.clip(probabilities, 1e-7, 1.0 - 1e-7)
    predictions = (probabilities >= threshold).astype(int)

    tn, fp, fn, tp = confusion_matrix(
        y_true, predictions, labels=[0, 1]
    ).ravel()

    metrics = {
        "test_windows": int(len(y_true)),
        "positive_labels": int(y_true.sum()),
        "negative_labels": int((y_true == 0).sum()),
        "threshold": float(threshold),
        "accuracy": float(accuracy_score(y_true, predictions)),
        "precision": float(
            precision_score(y_true, predictions, zero_division=0)
        ),
        "recall": float(
            recall_score(y_true, predictions, zero_division=0)
        ),
        "f1": float(
            f1_score(y_true, predictions, zero_division=0)
        ),
        "auroc": float(roc_auc_score(y_true, probabilities)),
        "auprc": float(
            average_precision_score(y_true, probabilities)
        ),
        "brier_score": float(
            brier_score_loss(y_true, probabilities)
        ),
        "log_loss": float(
            log_loss(y_true, probabilities, labels=[0, 1])
        ),
        "true_negative": int(tn),
        "false_positive": int(fp),
        "false_negative": int(fn),
        "true_positive": int(tp),
    }

    return metrics, predictions


# ============================================================
# Plot confusion matrix
# ============================================================

def save_confusion_matrix(
    subset: str,
    metrics: dict,
    output_path: Path,
) -> None:
    """Save a labelled confusion-matrix figure."""

    matrix = np.array([
        [metrics["true_negative"], metrics["false_positive"]],
        [metrics["false_negative"], metrics["true_positive"]],
    ])

    fig, ax = plt.subplots(figsize=(6, 5))

    image = ax.imshow(matrix, interpolation="nearest")
    fig.colorbar(image, ax=ax, fraction=0.046, pad=0.04)

    ax.set(
        xticks=[0, 1],
        yticks=[0, 1],
        xticklabels=["Predicted non-fault", "Predicted fault"],
        yticklabels=["Actual non-fault", "Actual fault"],
        xlabel="Predicted label",
        ylabel="Actual label",
        title=f"{subset}: Official Test Confusion Matrix",
    )

    ax.tick_params(axis="x", labelrotation=12)

    for row in range(2):
        for col in range(2):
            ax.text(
                col,
                row,
                f"{matrix[row, col]:,}",
                ha="center",
                va="center",
                color="black",
                fontsize=12,
            )

    fig.tight_layout()
    fig.savefig(output_path, dpi=200, bbox_inches="tight")
    plt.close(fig)


# ============================================================
# Evaluate one subset
# ============================================================

def evaluate_subset(subset: str) -> dict:
    print("\n" + "=" * 78)
    print(f"SensorGuard Official Test Evaluation — {subset}")
    print("=" * 78)

    checkpoint_path = (
        PROJECT_ROOT
        / "results"
        / "models"
        / subset
        / "baseline_lstm.pt"
    )

    output_dir = (
        PROJECT_ROOT
        / "results"
        / "metrics"
        / subset
        / "official_test_evaluation"
    )

    figure_dir = (
        PROJECT_ROOT
        / "results"
        / "figures"
        / subset
        / "official_test_evaluation"
    )

    output_dir.mkdir(parents=True, exist_ok=True)
    figure_dir.mkdir(parents=True, exist_ok=True)

    # Load official data.
    dataset = load_dataset(subset)

    train_df = dataset["train"].copy()
    test_df = dataset["test"].copy()
    rul_df = dataset["rul"].copy()

    train_df = train_df.sort_values(
        ["engine_id", "cycle"], kind="stable"
    ).reset_index(drop=True)

    test_df = test_df.sort_values(
        ["engine_id", "cycle"], kind="stable"
    ).reset_index(drop=True)

    # Reconstruct the original preprocessing pipeline.
    # The scaler is fitted only on the training-engine split.
    prepared = prepare_training_validation_test(
        train_df=train_df,
        test_df=test_df,
        rul_df=rul_df,
        sensor_columns=SENSOR_COLUMNS,
        horizon=HORIZON,
        train_ratio=TRAIN_RATIO,
        validation_ratio=VALIDATION_RATIO,
        window_size=WINDOW_SIZE,
        stride=STRIDE,
        random_seed=RANDOM_SEED,
    )

    X_test = np.asarray(prepared["X_test"])
    y_test = np.asarray(prepared["y_test"]).astype(int).reshape(-1)
    engine_ids = np.asarray(
        prepared["test_engine_ids"]
    ).reshape(-1)

    if len(X_test) != len(y_test) or len(y_test) != len(engine_ids):
        raise ValueError(
            f"{subset}: test windows, labels, and engine IDs "
            "have inconsistent lengths."
        )

    if len(X_test) == 0:
        raise ValueError(f"{subset}: no test windows generated.")

    print(f"Checkpoint:       {checkpoint_path}")
    print(f"Device:           {DEVICE}")
    print(f"Test windows:     {len(X_test):,}")
    print(f"Test engines:     {len(np.unique(engine_ids)):,}")
    print(f"Positive labels:  {int(y_test.sum()):,}")
    print(f"Negative labels:  {int((y_test == 0).sum()):,}")

    # Load and evaluate; no training occurs here.
    model = load_baseline(checkpoint_path)
    probabilities = predict_probabilities(model, X_test)

    metrics, predictions = calculate_metrics(
        y_test, probabilities
    )

    # Save per-window predictions.
    predictions_df = pd.DataFrame({
        "subset": subset,
        "engine_id": engine_ids,
        "true_label": y_test,
        "predicted_probability": probabilities,
        "predicted_label": predictions,
        "threshold": THRESHOLD,
        "correct": (y_test == predictions),
    })

    predictions_path = output_dir / "test_predictions.csv"
    predictions_df.to_csv(predictions_path, index=False)

    # Save metrics.
    metrics_path = output_dir / "test_metrics.json"
    with metrics_path.open("w", encoding="utf-8") as file:
        json.dump(metrics, file, indent=4, allow_nan=False)

    metrics_csv_path = output_dir / "test_metrics.csv"
    pd.DataFrame([metrics]).to_csv(
        metrics_csv_path, index=False
    )

    # Save confusion-matrix image.
    confusion_path = figure_dir / "confusion_matrix.png"
    save_confusion_matrix(
        subset, metrics, confusion_path
    )

    # Save an engine-level summary as well.
    engine_summary = (
        predictions_df.groupby("engine_id", as_index=False)
        .agg(
            windows=("true_label", "size"),
            true_positive_windows=("true_label", "sum"),
            mean_predicted_probability=(
                "predicted_probability", "mean"
            ),
            max_predicted_probability=(
                "predicted_probability", "max"
            ),
            predicted_fault_windows=("predicted_label", "sum"),
            correct_windows=("correct", "sum"),
        )
    )

    engine_summary["fraction_correct"] = (
        engine_summary["correct_windows"]
        / engine_summary["windows"]
    )

    engine_summary_path = output_dir / "engine_summary.csv"
    engine_summary.to_csv(engine_summary_path, index=False)

    report = {
        "project": "SensorGuard",
        "subset": subset,
        "evaluation": "official_cmapss_test",
        "checkpoint": str(checkpoint_path),
        "device": str(DEVICE),
        "threshold": THRESHOLD,
        "horizon": HORIZON,
        "window_size": WINDOW_SIZE,
        "stride": STRIDE,
        "training_validation_split_seed": RANDOM_SEED,
        "scaler_fit_on_training_split_only": True,
        "model_retrained": False,
        "test_used_for_model_selection": False,
        "metrics": metrics,
        "artifacts": {
            "predictions_csv": str(predictions_path),
            "engine_summary_csv": str(engine_summary_path),
            "metrics_json": str(metrics_path),
            "metrics_csv": str(metrics_csv_path),
            "confusion_matrix_png": str(confusion_path),
        },
    }

    report_path = output_dir / "evaluation_report.json"
    with report_path.open("w", encoding="utf-8") as file:
        json.dump(report, file, indent=4, allow_nan=False)

    print("\nOfficial test metrics:")
    for key in [
        "accuracy",
        "precision",
        "recall",
        "f1",
        "auroc",
        "auprc",
        "brier_score",
        "log_loss",
    ]:
        print(f"  {key:16s}: {metrics[key]:.6f}")

    print("\nConfusion matrix:")
    print(
        f"  TN={metrics['true_negative']:,}  "
        f"FP={metrics['false_positive']:,}"
    )
    print(
        f"  FN={metrics['false_negative']:,}  "
        f"TP={metrics['true_positive']:,}"
    )

    print(f"\nPredictions:       {predictions_path}")
    print(f"Engine summary:    {engine_summary_path}")
    print(f"Metrics report:    {report_path}")
    print(f"Confusion matrix:  {confusion_path}")

    return {
        "subset": subset,
        **metrics,
        "metrics_json": str(metrics_path),
        "predictions_csv": str(predictions_path),
    }


# ============================================================
# Run all subsets
# ============================================================

def main() -> None:
    print("=" * 78)
    print("SensorGuard — Official Test Evaluation")
    print("=" * 78)
    print(f"Project root: {PROJECT_ROOT}")
    print(f"Device:       {DEVICE}")
    print(f"Subsets:      {', '.join(SUBSETS)}")
    print(f"Threshold:    {THRESHOLD:.2f}")
    print("\nNo models will be retrained.")

    results = []

    for subset in SUBSETS:
        results.append(evaluate_subset(subset))

    summary_df = pd.DataFrame(results)

    summary_path = (
        PROJECT_ROOT
        / "results"
        / "metrics"
        / "official_test_evaluation_summary.csv"
    )

    summary_path.parent.mkdir(parents=True, exist_ok=True)
    summary_df.to_csv(summary_path, index=False)

    summary_json_path = (
        PROJECT_ROOT
        / "results"
        / "metrics"
        / "official_test_evaluation_summary.json"
    )

    with summary_json_path.open("w", encoding="utf-8") as file:
        json.dump(
            results,
            file,
            indent=4,
            allow_nan=False,
        )

    display_columns = [
        "subset",
        "accuracy",
        "precision",
        "recall",
        "f1",
        "auroc",
        "auprc",
        "brier_score",
        "log_loss",
    ]

    print("\n" + "=" * 100)
    print("ALL SUBSETS — OFFICIAL TEST RESULTS")
    print("=" * 100)

    print(
        summary_df[display_columns].to_string(
            index=False,
            float_format=lambda value: f"{value:.5f}",
        )
    )

    print(f"\nSummary CSV:  {summary_path}")
    print(f"Summary JSON: {summary_json_path}")
    print("\nOfficial test evaluation completed successfully.")


if __name__ == "__main__":
    main()
